// npm run test:model: real EmbeddingGemma 2 (LiteRT, WebGPU) in headless
// Windows Edge over the CC0 fixtures, judged by the shipped twin.ts rules.
// Needs the dev server (`npm run dev`, or BASE_URL=...) and web/.models/.
// Writes docs/eval.md and exits non-zero if a pass criterion fails.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const run = () => execFileSync("bash", ["scripts/edge-run.sh", "/model-eval.html", "EVAL_(DONE|FAIL)", "900"], { encoding: "utf8", maxBuffer: 64 << 20 });
let log = process.argv[2] ? readFileSync(process.argv[2], "utf8") : run();
const line = log.split("\n").find((l) => l.includes(" EVAL_RESULT "));
if (!line) {
  console.error(log.split("\n").filter((l) => !l.includes("_B64")).join("\n"));
  process.exit(2);
}
const r = JSON.parse(line.split(" EVAL_RESULT ")[1]);
const sha = execFileSync("git", ["rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
const date = new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC";
const BANDS = { uncanny: "Uncanny", cousins: "Cousins", distant: "Distant", strangers: "Strangers" };
const short = (n) => n.split("/")[1].replace(/^\d+-/, "").replace(/\.jpg$/, "");
const set = (s) => r.pairs.filter((p) => p.set === s);
const mean = (xs) => xs.reduce((a, b) => a + b, 0) / xs.length;

const twins = set("twins"), strangers = set("strangers"), same = set("same-kind");
const good = (p) => p.band === "cousins" || p.band === "uncanny"; // bands as shipped in data/twin-scoring.json
const crit = [
  ["Mean twin score ≥ mean stranger score + 20", `${mean(twins.map((p) => p.score)).toFixed(1)} vs ${mean(strangers.map((p) => p.score)).toFixed(1)}`, mean(twins.map((p) => p.score)) >= mean(strangers.map((p) => p.score)) + 20],
  ["≥ 6 of 8 twins score Cousins or better", `${twins.filter(good).length} of ${twins.length}`, twins.filter(good).length >= 6],
  ["≥ 6 of 8 strangers score Distant or worse", `${strangers.filter((p) => !good(p)).length} of ${strangers.length}`, strangers.filter((p) => !good(p)).length >= 6],
  ["≥ 3 of 4 same-kind pairs rejected as same kind", `${same.filter((p) => p.problem === "same-kind").length} of ${same.length}`, same.filter((p) => p.problem === "same-kind").length >= 3],
  ["All 4 reject images rejected or uncertain", `${r.rejects.filter((x) => x.problem).length} of ${r.rejects.length}`, r.rejects.every((x) => x.problem)],
  ["What they share: ≥ 1 attribute for ≥ 6 of 8 twins (sense judged in LOG.md)", `${twins.filter((p) => p.shared.length).length} of ${twins.length}`, twins.filter((p) => p.shared.length).length >= 6],
];
const row = (p) => `| ${short(p.a)} ↔ ${short(p.b)} | ${p.labelA} ↔ ${p.labelB} | ${p.sim.toFixed(3)} | **${p.score}** | ${BANDS[p.band]} | ${p.shared.length ? p.shared.join(" · ") : "Not much, honestly."} | ${p.problem ?? "–"} |`;
const head = "| Pair | Doppel sees | cosine | Score | Band | What they share | Rule |\n|---|---|---|---|---|---|---|";
const md = `# Model-in-the-loop eval

Real EmbeddingGemma 2 (text+vision 440M, LiteRT-LM, WebGPU) in headless Microsoft Edge on ${r.adapter}, over the CC0 fixtures in \`web/tests/fixtures/\`, judged by the functions the app ships (\`web/src/twin.ts\`, constants in \`data/twin-scoring.json\`). Generated by \`npm run test:model\` (\`web/scripts/model-eval.mjs\`).

Commit \`${sha}\`, ${date}.

## Pass criteria

| Criterion | Result | |
|---|---|---|
${crit.map(([c, v, ok]) => `| ${c} | ${v} | ${ok ? "PASS" : "**FAIL**"} |`).join("\n")}

## Twins (different kinds of thing that look alike)

${head}
${twins.map(row).join("\n")}

## Strangers (don't look alike)

${head}
${strangers.map(row).join("\n")}

## Same kind (should be refused)

${head}
${same.map(row).join("\n")}

## Not allowed or unreadable (should be refused)

| Image | Doppel sees | Kind | Margin | Rule |
|---|---|---|---|---|
${r.rejects.map((x) => `| ${short(x.name)} | ${x.label} | ${x.kind} | ${x.margin.toFixed(4)} | ${x.problem ?? "**accepted**"} |`).join("\n")}

## Timings (same run, not CPU-throttled)

- Model load from the browser cache: ${r.loadMs} ms
- Photo embed: median ${r.embedMedianMs} ms, max ${r.embedMaxMs} ms over ${r.images} photos
- Main-thread long tasks while embedding ${r.images} photos: ${r.longTasks.count}, longest ${r.longTasks.maxMs} ms, total ${r.longTasks.totalMs} ms
`;
writeFileSync("../docs/eval.md", md);
for (const [c, v, ok] of crit) console.log(`${ok ? "PASS" : "FAIL"}  ${c}: ${v}`);
console.log(`timings: load ${r.loadMs} ms, embed median ${r.embedMedianMs} ms max ${r.embedMaxMs} ms, long tasks ${JSON.stringify(r.longTasks)}`);
writeFileSync("report-eval.log", log);
process.exit(crit.every(([, , ok]) => ok) ? 0 : 1);
